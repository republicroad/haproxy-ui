import { createServer } from "node:http"

const PORT = Number(process.env.MOCK_PORT ?? 9090)
const USER = process.env.MOCK_USER ?? "admin"
const PASS = process.env.MOCK_PASS ?? "admin"

const frontends = []
const backends = new Map()
const acls = new Map() // "frontend|name" / "backend|name" -> acl[]
const runtimeMaps = new Map() // map name -> [{id,key,value}]
const userlists = [
  { name: "api_users", users: [{ username: "demo", password: "demopass", inactive: false, is_encrypted: false }] },
]
const resolversStore = [
  {
    name: "local_dns",
    nameservers: [{ name: "ns1", address: "127.0.0.11:53" }],
    accepted_payload_size: 8192,
    hold_valid: "10s",
    hold_obsolete: "15s",
    hold_refresh: "30s",
    hold_retry: "1s",
  },
]
const sslCerts = [
  {
    name: "example.pem",
    description: "self-signed sample",
    pem: `-----BEGIN CERTIFICATE-----
MIIB0zCCAX2gAwIBAgIUKvYuS9k0o1_example_sample_cert_data_QQowDQYJ
KoZIhvcNAQELBQAwGDEWMBQGA1UEAwwNYXJjaGl0ZWN0dXJlMB4XDTI0MDEwMTAw
MDAwMFoXDTI1MDEwMTAwMDAwMFowGDEWMBQGA1UEAwwNYXJjaGl0ZWN0dXJlMBww
GgYJKoZIhvcNAQkBFg10ZXN0QGV4YW1wbGUuY29tMBwwGgYJKoZIhvcNAQkBFg10
-----END CERTIFICATE-----`,
  },
]

function runtimeServer(beName, s) {
  const admin = s.admin_state ?? "ready"
  const oper = admin === "ready" ? "ready" : "down"
  return {
    name: s.name,
    address: s.address,
    port: s.port,
    weight: s.weight ?? 100,
    operational_state: oper,
    admin_state: admin,
    check_status: admin === "ready" ? "L4OK" : "MAINT",
    fqdn: "-",
    backend_name: beName,
    id: "1",
  }
}

function send(res, status, body) {
  const payload = typeof body === "string" ? body : JSON.stringify(body)
  res.writeHead(status, {
    "content-type": typeof body === "string" ? "text/plain" : "application/json",
  })
  res.end(payload)
}

const server = createServer((req, res) => {
  const auth = req.headers["authorization"]
  const expected = "Basic " + Buffer.from(`${USER}:${PASS}`).toString("base64")
  if (auth !== expected) return send(res, 401, { code: 401, message: "unauthorized" })

  const url = new URL(req.url, `http://localhost:${PORT}`)
  const p = url.pathname.replace(/^\/v[23]\//, "")
  const method = req.method

  let body = ""
  req.on("data", (c) => (body += c))
  req.on("end", () => {
    let json = {}
    try {
      if (body) json = JSON.parse(body)
    } catch {
      // raw-body endpoints (PEM upload) carry non-JSON payloads
      if (!(p === "services/haproxy/storage/ssl" && method === "POST")) {
        return send(res, 400, { code: 400, message: "bad json" })
      }
    }

    // transactions
    if (p === "services/haproxy/transactions" && method === "POST") {
      const id = "tx_" + Math.random().toString(36).slice(2, 10)
      return send(res, 201, { id, version: 1 })
    }
    const txMatch = p.match(/^services\/haproxy\/transactions\/(.+)$/)
    if (txMatch) {
      if (method === "PUT") return send(res, 200, { id: txMatch[1], status: "success" })
      if (method === "DELETE") return send(res, 200, { id: txMatch[1], status: "cancelled" })
    }

    // configuration version (used by transaction workflows)
    if (p === "services/haproxy/configuration/version" && method === "GET") {
      return send(res, 200, 1)
    }

    // runtime info (shape mirrors real dataplaneapi: nested under "info")
    if (p === "services/haproxy/runtime/info" && method === "GET") {
      return send(res, 200, {
        info: {
          version: "2.8.4",
          build_date: "2024-01-01",
          node: "mock-1",
          uptime: 12345,
        },
        pools: { frontend: 1, backend: 2, server: 3 },
      })
    }

    // raw config
    if (p === "services/haproxy/configuration/raw" && method === "GET") {
      const fes = frontends
        .map((f) => `frontend ${f.name}\n  mode ${f.mode}\n  bind ${f.bind?.[0]?.address}:${f.bind?.[0]?.port}`)
        .join("\n")
      const bes = [...backends.values()]
        .map((b) => {
          const srvs = (b.servers || [])
            .map((s) => `  server ${s.name} ${s.address}:${s.port} weight ${s.weight}`)
            .join("\n")
          return `backend ${b.name}\n  mode ${b.mode}\n${srvs}`
        })
        .join("\n")
      return send(res, 200, `# generated by mock-dataplaneapi\n${fes}\n${bes}\n`)
    }

    // frontends
    if (p === "services/haproxy/configuration/frontends" && method === "GET") {
      return send(res, 200, frontends)
    }
    if (p === "services/haproxy/configuration/frontends" && method === "POST") {
      frontends.push(json)
      return send(res, 201, json)
    }
    const feMatch = p.match(/^services\/haproxy\/configuration\/frontends\/([^/]+)$/)
    if (feMatch && method === "GET") {
      const f = frontends.find((x) => x.name === decodeURIComponent(feMatch[1]))
      if (!f) return send(res, 404, { code: 404, message: "frontend not found" })
      return send(res, 200, f)
    }
    if (feMatch && method === "DELETE") {
      const i = frontends.findIndex((f) => f.name === decodeURIComponent(feMatch[1]))
      if (i >= 0) frontends.splice(i, 1)
      return send(res, 202, {})
    }
    if (feMatch && method === "PUT") {
      const name = decodeURIComponent(feMatch[1])
      const i = frontends.findIndex((f) => f.name === name)
      if (i < 0) return send(res, 404, { code: 404, message: "frontend not found" })
      if (url.searchParams.get("full_section") === "true") {
        // full_section=true semantics: entire section replaced. Accept the
        // v3-style binds map and store it as the v2-style bind array.
        const { binds, ...rest } = json
        const bindArr = binds
          ? Object.entries(binds).map(([k, v]) => ({ name: k, ...v }))
          : undefined
        frontends[i] = { ...frontends[i], ...rest, name, ...(bindArr ? { bind: bindArr } : {}) }
      } else {
        // full_section=false semantics: only section fields replaced
        frontends[i] = { ...frontends[i], ...json, name }
      }
      return send(res, 200, frontends[i])
    }

    // backends
    if (p === "services/haproxy/configuration/backends" && method === "GET") {
      return send(res, 200, [...backends.values()])
    }
    if (p === "services/haproxy/configuration/backends" && method === "POST") {
      const b = { ...json, servers: [] }
      backends.set(b.name, b)
      return send(res, 201, b)
    }
    const srvMatch = p.match(
      /^services\/haproxy\/configuration\/backends\/(.+)\/servers\/?(.+)?$/,
    )
    if (srvMatch) {
      const beName = decodeURIComponent(srvMatch[1])
      const be = backends.get(beName)
      if (!be) return send(res, 404, { code: 404, message: "backend not found" })
      if (method === "GET") return send(res, 200, be.servers)
      if (method === "POST") {
        be.servers.push(json)
        return send(res, 201, json)
      }
      if (method === "PUT" && srvMatch[2]) {
        const sName = decodeURIComponent(srvMatch[2])
        const s = (be.servers || []).find((x) => x.name === sName)
        if (!s) return send(res, 404, { code: 404, message: "server not found" })
        // provided-field update (check params, port, weight, address...)
        be.servers = (be.servers || []).map((x) =>
          x.name === sName ? { ...x, ...json, name: sName } : x,
        )
        return send(res, 200, be.servers.find((x) => x.name === sName))
      }
      if (method === "DELETE" && srvMatch[2]) {
        const sName = decodeURIComponent(srvMatch[2])
        be.servers = be.servers.filter((s) => s.name !== sName)
        return send(res, 202, {})
      }
    }

    const beMatch = p.match(/^services\/haproxy\/configuration\/backends\/([^/]+)$/)
    if (beMatch && method === "DELETE") {
      backends.delete(decodeURIComponent(beMatch[1]))
      return send(res, 202, {})
    }
    if (beMatch && method === "PUT") {
      const name = decodeURIComponent(beMatch[1])
      const be = backends.get(name)
      if (!be) return send(res, 404, { code: 404, message: "backend not found" })
      // full_section=false semantics: servers untouched
      backends.set(name, {
        ...be,
        mode: json.mode ?? be.mode,
        balance: json.balance ?? be.balance,
        description: json.description ?? be.description,
        stick_table: json.stick_table ?? be.stick_table,
      })
      return send(res, 200, backends.get(name))
    }

    // runtime per-backend server states (mirrors real dataplaneapi fields)
    const rtSrvMatch = p.match(
      /^services\/haproxy\/runtime\/backends\/(.+)\/servers\/?(.+)?$/,
    )
    if (rtSrvMatch && method === "GET") {
      const beName = decodeURIComponent(rtSrvMatch[1])
      const be = backends.get(beName)
      if (!be) return send(res, 404, { code: 404, message: "backend not found" })
      if (rtSrvMatch[2]) {
        const sName = decodeURIComponent(rtSrvMatch[2])
        const s = (be.servers || []).find((x) => x.name === sName)
        if (!s) return send(res, 404, { code: 404, message: "server not found" })
        return send(res, 200, runtimeServer(beName, s))
      }
      const runtime = (be.servers || []).map((s) => runtimeServer(beName, s))
      return send(res, 200, runtime)
    }
    if (rtSrvMatch && method === "PUT" && rtSrvMatch[2]) {
      const beName = decodeURIComponent(rtSrvMatch[1])
      const be = backends.get(beName)
      if (!be) return send(res, 404, { code: 404, message: "backend not found" })
      const sName = decodeURIComponent(rtSrvMatch[2])
      const s = (be.servers || []).find((x) => x.name === sName)
      if (!s) return send(res, 404, { code: 404, message: "server not found" })
      if (
        json.admin_state &&
        !["ready", "maint", "drain"].includes(json.admin_state)
      ) {
        return send(res, 400, { code: 400, message: "invalid admin_state" })
      }
      s.admin_state = json.admin_state ?? s.admin_state ?? "ready"
      if (json.weight !== undefined) s.weight = json.weight
      return send(res, 200, runtimeServer(beName, s))
    }

    // config rule subresources per parent section (frontend/backend):
    // http_request_rules, http_response_rules, tcp_request_rules,
    // backend_switching_rules, http_checks, tcp_checks
    const ruleMatch = p.match(
      /^services\/haproxy\/configuration\/(frontends|backends)\/([^/]+)\/(http_request_rules|http_response_rules|tcp_request_rules|backend_switching_rules|http_checks|tcp_checks)\/?(\d+)?$/,
    )
    if (ruleMatch) {
      const key = `rules|${ruleMatch[3]}|${ruleMatch[1]}|${decodeURIComponent(ruleMatch[2])}`
      if (!acls.has(key)) acls.set(key, [])
      const list = acls.get(key)
      if (method === "GET" && ruleMatch[4] === undefined) {
        return send(res, 200, list)
      }
      if (method === "POST") {
        list.push(json)
        return send(res, 201, json)
      }
      if (method === "PUT" && ruleMatch[4] !== undefined) {
        const i = Number(ruleMatch[4])
        if (i > list.length) return send(res, 400, { code: 400, message: "index out of range" })
        list.splice(i, i === list.length ? 0 : 1, json)
        return send(res, 200, json)
      }
      if (method === "DELETE" && ruleMatch[4] !== undefined) {
        list.splice(Number(ruleMatch[4]), 1)
        return send(res, 202, {})
      }
    }

    // SSL storage (simplified: the app's cert wrapper posts raw PEM with
    // ?name=; the real dataplaneapi uses multipart uploads)
    if (p === "services/haproxy/storage/ssl" && method === "GET") {
      return send(res, 200, sslCerts.map((c) => ({
        id: c.name,
        storage_name: c.name,
        description: c.description ?? "",
      })))
    }
    if (p === "services/haproxy/storage/ssl" && method === "POST") {
      const name = url.searchParams.get("name") ?? `cert_${Date.now()}`
      if (sslCerts.some((c) => c.name === name)) {
        return send(res, 409, { code: 409, message: "certificate already exists" })
      }
      sslCerts.push({ name, pem: body, description: `uploaded ${new Date().toISOString()}` })
      return send(res, 201, { id: name, storage_name: name })
    }
    const sslMatch = p.match(/^services\/haproxy\/storage\/ssl\/([^/]+)$/)
    if (sslMatch) {
      const name = decodeURIComponent(sslMatch[1])
      const cert = sslCerts.find((c) => c.name === name)
      if (!cert) return send(res, 404, { code: 404, message: "certificate not found" })
      if (method === "GET") return send(res, 200, cert.pem)
      if (method === "DELETE") {
        sslCerts.splice(sslCerts.indexOf(cert), 1)
        return send(res, 202, {})
      }
    }

    // resolvers configuration (global objects)
    if (p === "services/haproxy/configuration/resolvers" && method === "GET") {
      return send(res, 200, resolversStore)
    }
    if (p === "services/haproxy/configuration/resolvers" && method === "POST") {
      if (resolversStore.some((r) => r.name === json.name)) {
        return send(res, 409, { code: 409, message: "resolver already exists" })
      }
      const r = { name: json.name, ...json }
      resolversStore.push(r)
      return send(res, 201, r)
    }
    const resMatch = p.match(/^services\/haproxy\/configuration\/resolvers\/([^/]+)$/)
    if (resMatch) {
      const name = decodeURIComponent(resMatch[1])
      const r = resolversStore.find((x) => x.name === name)
      if (!r) return send(res, 404, { code: 404, message: "resolver not found" })
      if (method === "GET") return send(res, 200, r)
      if (method === "PUT") {
        Object.assign(r, json, { name })
        return send(res, 200, r)
      }
      if (method === "DELETE") {
        resolversStore.splice(resolversStore.indexOf(r), 1)
        return send(res, 202, {})
      }
    }

    // userlists (+users) configuration
    if (p === "services/haproxy/configuration/userlists" && method === "GET") {
      return send(res, 200, userlists.map((u) => ({ name: u.name, users: u.users })))
    }
    if (p === "services/haproxy/configuration/userlists" && method === "POST") {
      if (userlists.some((u) => u.name === json.name)) {
        return send(res, 409, { code: 409, message: "userlist already exists" })
      }
      userlists.push({ name: json.name, users: [] })
      return send(res, 201, { name: json.name })
    }
    const ulMatch = p.match(
      /^services\/haproxy\/configuration\/userlists\/([^/]+)\/users\/?([^/]+)?$/,
    )
    if (ulMatch) {
      const name = decodeURIComponent(ulMatch[1])
      const ul = userlists.find((u) => u.name === name)
      if (!ul) return send(res, 404, { code: 404, message: "userlist not found" })
      if (method === "GET" && ulMatch[2] === undefined) {
        return send(res, 200, ul.users)
      }
      if (method === "POST") {
        if (ul.users.some((x) => x.username === json.username)) {
          return send(res, 409, { code: 409, message: "user already exists" })
        }
        ul.users.push(json)
        return send(res, 201, json)
      }
      const uname = ulMatch[2] ? decodeURIComponent(ulMatch[2]) : null
      if (method === "DELETE" && uname) {
        const i = ul.users.findIndex((x) => x.username === uname)
        if (i < 0) return send(res, 404, { code: 404, message: "user not found" })
        ul.users.splice(i, 1)
        return send(res, 202, {})
      }
    }
    const ulListMatch = p.match(/^services\/haproxy\/configuration\/userlists\/([^/]+)$/)
    if (ulListMatch) {
      const name = decodeURIComponent(ulListMatch[1])
      const ul = userlists.find((u) => u.name === name)
      if (!ul) return send(res, 404, { code: 404, message: "userlist not found" })
      if (method === "GET") return send(res, 200, ul)
      if (method === "DELETE") {
        userlists.splice(userlists.indexOf(ul), 1)
        return send(res, 202, {})
      }
    }

    // log targets per parent section (frontend/backend)
    const logMatch = p.match(
      /^services\/haproxy\/configuration\/(frontends|backends)\/([^/]+)\/logs\/?(\d+)?$/,
    )
    if (logMatch) {
      const key = `logs|${logMatch[1]}|${decodeURIComponent(logMatch[2])}`
      if (!acls.has(key)) acls.set(key, [])
      const list = acls.get(key)
      if (method === "GET" && logMatch[3] === undefined) {
        return send(res, 200, list)
      }
      if (method === "POST") {
        list.push(json)
        return send(res, 201, json)
      }
      if (method === "DELETE" && logMatch[3] !== undefined) {
        list.splice(Number(logMatch[3]), 1)
        return send(res, 202, {})
      }
    }

    const aclMatch = p.match(
      /^services\/haproxy\/configuration\/(frontends|backends)\/([^/]+)\/acls\/?(\d+)?$/,
    )
    if (aclMatch) {
      const key = `${aclMatch[1]}|${decodeURIComponent(aclMatch[2])}`
      if (!acls.has(key)) acls.set(key, [])
      const list = acls.get(key)
      if (method === "GET" && aclMatch[3] === undefined) {
        return send(res, 200, list)
      }
      if (method === "POST") {
        list.push(json)
        return send(res, 201, json)
      }
      if (method === "DELETE" && aclMatch[3] !== undefined) {
        list.splice(Number(aclMatch[3]), 1)
        return send(res, 202, {})
      }
    }

    // runtime maps: list + per-map entry CRUD
    if (p === "services/haproxy/runtime/maps" && method === "GET") {
      return send(res, 200, [...runtimeMaps.keys()].map((name) => ({
        id: name,
        file: `/etc/haproxy/maps/${name}`,
        storage_name: name,
        description: `mock map ${name}`,
      })))
    }
    const mapListMatch = p.match(/^services\/haproxy\/runtime\/maps\/([^/]+)\/entries\/?([^/]+)?$/)
    if (mapListMatch) {
      const name = decodeURIComponent(mapListMatch[1])
      if (!runtimeMaps.has(name)) runtimeMaps.set(name, [])
      const entries = runtimeMaps.get(name)
      if (method === "GET" && mapListMatch[2] === undefined) {
        return send(res, 200, entries)
      }
      if (method === "POST") {
        const entry = { id: json.key, key: json.key, value: json.value }
        entries.push(entry)
        return send(res, 201, entry)
      }
      const eid = mapListMatch[2] ? decodeURIComponent(mapListMatch[2]) : null
      if (method === "PUT" && eid) {
        const e = entries.find((x) => x.id === eid)
        if (!e) return send(res, 404, { code: 404, message: "entry not found" })
        e.value = json.value
        return send(res, 200, e)
      }
      if (method === "DELETE" && eid) {
        const i = entries.findIndex((x) => x.id === eid)
        if (i < 0) return send(res, 404, { code: 404, message: "entry not found" })
        entries.splice(i, 1)
        return send(res, 202, {})
      }
    }

    // native stats (shape mirrors models.NativeStats)
    if (p === "services/haproxy/stats/native" && method === "GET") {
      const stats = []
      let tick = 0
      const jitter = () => Math.floor(Math.random() * 500) + tick++
      for (const f of frontends) {
        stats.push({
          type: "frontend",
          name: f.name,
          backend_name: f.name,
          stats: {
            scur: jitter() % 20,
            smax: 42,
            stot: 1000 + jitter(),
            req_rate: jitter() % 50,
            bin: 4096 * (1 + jitter() % 10),
            bout: 8192 * (1 + jitter() % 10),
            hrsp_1xx: 1,
            hrsp_2xx: 900 + jitter() % 50,
            hrsp_4xx: jitter() % 10,
            hrsp_5xx: jitter() % 3,
            status: "OPEN",
          },
        })
      }
      for (const b of backends.values()) {
        stats.push({
          type: "backend",
          name: b.name,
          backend_name: b.name,
          stats: {
            stot: 800 + jitter(),
            bin: 2048 * (1 + jitter() % 10),
            bout: 4096 * (1 + jitter() % 10),
            hrsp_2xx: 700 + jitter() % 40,
            hrsp_5xx: jitter() % 5,
            status: "UP",
          },
        })
        for (const s of b.servers ?? []) {
          const admin = s.admin_state ?? "ready"
          stats.push({
            type: "server",
            name: s.name,
            backend_name: b.name,
            stats: {
              stot: 400 + jitter(),
              weight: s.weight ?? 100,
              status: admin === "ready" ? "UP" : "MAINT",
              req_rate: jitter() % 30,
              bin: 1024 * (1 + jitter() % 5),
              bout: 2048 * (1 + jitter() % 5),
            },
          })
        }
      }
      return send(res, 200, { runtimeAPI: "/tmp/haproxy.sock", stats })
    }

    // config HTTP request rules per parent section (frontend/backend)

    // stick tables (read-only in mock)
    if (p === "services/haproxy/runtime/stick_tables" && method === "GET") {
      return send(res, 200, [
        {
          name: "ft_polysoft",
          size: 100,
          used: 2,
          type: "ip",
          fields: [
            { field: "conn_cnt", type: "counter" },
            { field: "http_req_rate", type: "rate", period: 10 },
          ],
        },
      ])
    }
    const stickMatch = p.match(
      /^services\/haproxy\/runtime\/stick_tables\/([^/]+)\/entries$/,
    )
    if (stickMatch && method === "GET") {
      const all = [
        {
          id: "1",
          key: "10.0.0.15",
          use: true,
          exp: 28,
          conn_cnt: 5,
          http_req_rate: 12,
        },
        {
          id: "2",
          key: "10.0.0.22",
          use: true,
          exp: 55,
          conn_cnt: 2,
          http_req_rate: 4,
        },
        {
          id: "3",
          key: "10.0.0.99",
          use: false,
          exp: 0,
          conn_cnt: 0,
          http_req_rate: 0,
        },
      ]
      const count = url.searchParams.get("count")
      const offset = Number(url.searchParams.get("offset") ?? 0)
      let rows = all
      if (offset > 0) rows = rows.slice(offset)
      if (count !== null) rows = rows.slice(0, Math.max(1, Number(count)))
      return send(res, 200, rows)
    }

    return send(res, 404, { code: 404, message: `no mock for ${method} ${p}` })
  })
})

server.listen(PORT, () => console.log(`mock-dataplaneapi on :${PORT}`))
